"""Requirements traceability matrix: bms/requirements.yaml x test tags ("verifies: ...")
in bms/tests/unit/*.c and bms/tests/py/*.py x test results (host, target) x analysis
checks on results files. Writes results/bms/trace.json and results/bms/TRACE.md.

A requirement is COVERED when at least one test or analysis check is linked to it, and
PASSES when every linked item passed (tests on the host and on the emulated target).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "results" / "bms"
TAG = re.compile(r"verifies:\s*([A-Z0-9\-, ]+)")
C_TEST = re.compile(r"BMS_TEST\(\s*\w+\s*,\s*(test_\w+)\s*\)")
PY_TEST = re.compile(r"^def (test_\w+)", re.M)


def tagged_tests() -> dict[str, list[tuple[str, str]]]:
    """requirement id -> [(kind, test name)]"""
    out: dict[str, list[tuple[str, str]]] = {}
    for kind, pattern, files in (
        ("c", C_TEST, (ROOT / "bms" / "tests" / "unit").glob("*.c")),
        ("py", PY_TEST, (ROOT / "bms" / "tests" / "py").glob("*.py")),
    ):
        for f in sorted(files):
            pending: list[str] = []
            for line in f.read_text().splitlines():
                m = TAG.search(line)
                if m:
                    pending += [x.strip() for x in m.group(1).split(",") if x.strip()]
                    continue
                t = pattern.search(line)
                if t:
                    for rid in pending:
                        out.setdefault(rid, []).append((kind, t.group(1)))
                    pending = []
    return out


def main() -> int:
    spec = yaml.safe_load((ROOT / "bms" / "requirements.yaml").read_text())
    reqs = spec["requirements"]
    analysis = spec.get("analysis", {})
    tags = tagged_tests()
    host = json.loads((RES / "host_tests.json").read_text())
    target = json.loads((RES / "target_tests.json").read_text())
    c_host = set(host["c_unit"]["passed"])
    c_tgt = set(target.get("passed_tests", []))
    py_ok = {k for k, v in host["python"].get("functions", {}).items() if v}
    unknown = sorted(set(tags) - {r["id"] for r in reqs})
    rows = []
    for r in reqs:
        rid = r["id"]
        items = []
        for kind, name in tags.get(rid, []):
            if kind == "c":
                items.append(
                    {
                        "type": "test (host + emulated Cortex-M3)",
                        "name": name,
                        "host": name in c_host,
                        "target": name in c_tgt,
                        "pass": name in c_host and name in c_tgt,
                    }
                )
            else:
                items.append({"type": "test (host, Python/DBC)", "name": name, "pass": name in py_ok})
        for a in analysis.get(rid, []):
            d = json.loads((ROOT / a["file"]).read_text())
            try:
                ok = bool(
                    eval(
                        a["check"],
                        {"json": json, "all": all, "any": any, "len": len, "set": set},  # noqa: S307
                        {"d": d},
                    )
                )
            except Exception as e:  # missing key = not verified
                ok, a = False, dict(a, error=str(e))
            items.append({"type": "analysis", "name": a["name"], "file": a["file"], "pass": ok})
        rows.append(
            {
                "id": rid,
                "title": r["title"],
                "text": r["text"],
                "covered": bool(items),
                "pass": bool(items) and all(i["pass"] for i in items),
                "verified_by": items,
            }
        )
    n = len(rows)
    out = {
        "requirements": n,
        "covered": sum(r["covered"] for r in rows),
        "passing": sum(r["pass"] for r in rows),
        "not_passing": [r["id"] for r in rows if not r["pass"]],
        "unknown_ids_in_tests": unknown,
        "tests_linked": len({(k, t) for v in tags.values() for k, t in v}),
        "rows": rows,
    }
    (RES / "trace.json").write_text(json.dumps(out, indent=1))
    md = [
        "# BMS requirements traceability",
        "",
        f"Generated by `bms/tools/trace.py`. {out['covered']}/{n} requirements covered, "
        f"{out['passing']}/{n} passing. Not passing: {', '.join(out['not_passing']) or 'none'}.",
        "",
        "| Requirement | Title | Verified by | Status |",
        "|---|---|---|---|",
    ]
    for r in rows:
        tests = [i for i in r["verified_by"] if i["type"].startswith("test")]
        ana = [i for i in r["verified_by"] if i["type"] == "analysis"]
        parts = []
        if tests:
            parts.append(f"{len(tests)} tests ({sum(i['pass'] for i in tests)} pass)")
        for a in ana:
            parts.append(f"analysis: {a['name']} ({'pass' if a['pass'] else 'FAIL'})")
        md.append(
            f"| {r['id']} | {r['title']} | {'; '.join(parts) or 'NOT COVERED'} | "
            f"{'pass' if r['pass'] else ('FAIL' if r['covered'] else 'not covered')} |"
        )
    md += ["", "Test names per requirement are in `results/bms/trace.json`."]
    (RES / "TRACE.md").write_text("\n".join(md) + "\n")
    print(json.dumps({k: v for k, v in out.items() if k != "rows"}))
    return 0 if out["covered"] == n and not unknown else 1


if __name__ == "__main__":
    sys.exit(main())
