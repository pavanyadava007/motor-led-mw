"""Collect results/bms/*.json into results/bms/RESULTS.md and results/bms/summary.json.
Every number in the BMS section of the README comes from these files."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "results" / "bms"


def load(name: str) -> dict:
    return json.loads((RES / name).read_text())


def f2(x: float) -> str:
    return f"{x:.2f}"


def main() -> None:
    soc, prof, mut = load("soc_eval.json"), load("profile.json"), load("mutation.json")
    mut0, sa, trace = (
        load("mutation_without_detail_tests.json"),
        load("static_analysis.json"),
        load("trace.json"),
    )
    host, tgt, fit = load("host_tests.json"), load("target_tests.json"), load("ecm_fit.json")
    runs = {(r["temp"], r["cycle"], r["scenario"]): r for r in soc["runs"]}
    cycles = [(t, c) for t, cs in soc["held_out"].items() for c in cs]
    g = prof["insn_counts_cortex_m4f_O2_emulated"]["groups"]
    g0 = load("profile_crc_bitwise.json")["groups"]
    par = soc["parity_target_vs_host"]
    L = [
        "# BMS results",
        "",
        "Generated by `bms/tools/make_results.py` from the JSON files in this folder.",
        "",
        "## SoC on held-out drive cycles (REAL data)",
        "",
        f"Data: {soc['data']}",
        "",
        "ECM (1-RC) and EKF noise were fitted on the C/20 and HPPC tests only "
        f"(HPPC voltage fit RMSE {fit['25degC']['rc_fit']['fit_rmse_v'] * 1000:.1f} mV at 25 degC, "
        f"{fit['0degC']['rc_fit']['fit_rmse_v'] * 1000:.1f} mV at 0 degC). Reference SoC = 1 + Ah/Q from the "
        "tester's Ah counter. SoC error in % SoC; C code on the host.",
        "",
        "| Cycle | CC RMSE, start -20 % | EKF RMSE, start -20 % | EKF max error after 10 min | "
        "CC RMSE, -50 mA offset | EKF RMSE, -50 mA offset |",
        "|---|---|---|---|---|---|",
    ]
    for t, c in cycles:
        a, b = runs[(t, c, "init_minus20")], runs[(t, c, "init_true_bias_minus50mA")]
        L.append(
            f"| {c} {t.replace('degC', ' degC')} | {f2(a['cc']['rmse_pct'])} | {f2(a['ekf']['rmse_pct'])} | "
            f"{f2(a['ekf']['max_abs_after_600s_pct'])} | {f2(b['cc']['rmse_pct'])} | {f2(b['ekf']['rmse_pct'])} |"
        )
    L += [
        "",
        f"Excluded: {soc['excluded']}.",
        "",
        f"Target parity: {par['outputs_compared']:,} float32 outputs from the emulated Cortex-M4F "
        f"(QEMU mps2-an386) vs the x86-64 host: bit-exact fraction {par['bit_exact_fraction']}, "
        f"max abs diff {par['max_abs_diff']}. C float32 vs Python float64 mirror: max SoC diff "
        f"{soc['c_float32_vs_python_float64_max_abs_soc_diff']:.2e}.",
        "",
        "## Tests",
        "",
        f"- C unit tests on the host: {len(host['c_unit']['passed'])} pass, {len(host['c_unit']['failed'])} fail"
        + (
            f"; with ASan+UBSan: {len(host['c_unit_asan_ubsan']['passed'])} pass"
            if "c_unit_asan_ubsan" in host
            else ""
        ),
        f"- Same tests as ztest on QEMU mps2-an385 (Cortex-M3, emulated): {tgt['passed']} pass, {tgt['failed']} fail",
        f"- Python cross-checks (DBC decode with cantools, CRC reference): {len(host['python']['passed'])} pass",
        f"- Mutation score (bms/src, {mut['mutants']} non-equivalent mutants, host runner): "
        f"{mut['killed']}/{mut['mutants']} = {mut['score'] * 100:.1f} % "
        f"(without the detail tests written after the first run: {mut0['killed']}/{mut0['mutants']} = "
        f"{mut0['score'] * 100:.1f} %)",
        f"- Requirements: {trace['covered']}/{trace['requirements']} covered, {trace['passing']} passing, "
        f"not passing: {', '.join(trace['not_passing']) or 'none'} (see TRACE.md)",
        "",
        "## Profile (emulated, Cortex-M4F, arm-none-eabi-gcc 13.3 -O2)",
        "",
        "QEMU TCG plugin instruction counts, NOT cycles or time.",
        "",
        "| Part | Instructions per call | Before (bit-serial CRC) |",
        "|---|---|---|",
    ]
    names = {
        "bms_cycle": "bms_cycle (12 cells, whole cycle)",
        "ekf_step": "EKF step (one cell)",
        "monitor": "monitoring",
        "state_machine": "state machine",
        "balance": "balancing",
        "crc_e2e": "E2E/CRC (1 RX check + 3 TX frames)",
    }
    for k, n in names.items():
        L.append(f"| {n} | {g[k]['insns_per_call']:,} | {g0[k]['insns_per_call']:,} |")
    sz = prof["size_bytes"]
    st = prof["stack_cortex_m4f_Os"]
    L += ["", "| Size (text incl. ECM tables, bytes) | -Os | -O2 |", "|---|---|---|"]
    for cpu in ("cortex-m4f", "cortex-m33", "cortex-m3"):
        L.append(f"| {cpu} | {sz[cpu + ' -Os']['total']['text']:,} | {sz[cpu + ' -O2']['total']['text']:,} |")
    L += [
        "",
        f"Data/bss in the library: {sz['cortex-m4f -Os']['total']['data']} / {sz['cortex-m4f -Os']['total']['bss']} "
        f"bytes. RAM context `bms_t`: {prof['ram_bms_context_bytes']} bytes. Worst-case stack of bms_cycle(): "
        f"{st['bms_cycle_worst_case_bytes']} bytes at -Os ({' > '.join(st['worst_path'])}), "
        f"{prof['stack_cortex_m4f_O2']['bms_cycle_worst_case_bytes']} at -O2. External symbols: "
        f"{', '.join(prof['external_symbols_needed']) or 'none'}.",
        "",
        "## Static analysis",
        "",
        f"- Strict compile warnings: host gcc {sa['strict_compile']['host_gcc']['warnings']}, arm-none-eabi-gcc "
        f"{sa['strict_compile']['arm_none_eabi_gcc']['warnings']} (`{sa['strict_compile']['host_gcc']['flags']}`)",
        f"- {sa['cppcheck_version']} --enable=all: {sa['cppcheck']['findings']} findings",
        f"- MISRA C 2012 addon: {sa['misra_addon']['findings']} findings, open: "
        + ", ".join(
            f"{k.replace('misra-c2012-', 'rule ')} x{v}" for k, v in sa["misra_addon"]["by_id"].items()
        ),
    ]
    (RES / "RESULTS.md").write_text("\n".join(L) + "\n")
    summary = {
        "soc": {
            f"{t}/{c}": {
                "cc_rmse_init_minus20": runs[(t, c, "init_minus20")]["cc"]["rmse_pct"],
                "ekf_rmse_init_minus20": runs[(t, c, "init_minus20")]["ekf"]["rmse_pct"],
            }
            for t, c in cycles
        },
        "parity_bit_exact_fraction": par["bit_exact_fraction"],
        "tests_host": len(host["c_unit"]["passed"]),
        "tests_target": tgt["passed"],
        "mutation_score": mut["score"],
        "requirements": [trace["covered"], trace["passing"], trace["requirements"]],
        "insns_per_cycle": g["bms_cycle"]["insns_per_call"],
    }
    (RES / "summary.json").write_text(json.dumps(summary, indent=1))
    print("\n".join(L))


if __name__ == "__main__":
    main()
